/**
 * Shared types + scoring rubric for AI presentation analysis.
 *
 * Imported by BOTH the API routes (server) and the dashboard (client),
 * so this file must stay free of secrets, fetch calls and Node APIs.
 */

/* ---------- Conversation ------------------------------------------------ */

export type SpeakerRole = "salesperson" | "customer";

/** One spoken turn. `speaker` is the raw diarization label ("A", "B"…);
 *  map it to a role through the session's speaker map. */
export type DialogueTurn = {
  speaker: string;
  start_ms: number;
  end_ms: number;
  text: string;
};

export type Dialogue = {
  /** How the speaker labels were decided:
   *   • "assemblyai"    — real voice-based speaker separation (not currently used).
   *   • "nvidia"        — NVIDIA NIM (Llama / Qwen / Mixtral) split a plain transcript.
   *   • "gemini"        — Google Gemini split a plain transcript.
   *   • "heuristic"     — our free rule-based splitter (approximate).
   *   • "text-inferred" — legacy alias, kept for old rows. */
  source: "assemblyai" | "nvidia" | "gemini" | "heuristic" | "text-inferred";
  language: string | null;
  turns: DialogueTurn[];
};

export type SpeakerMap = Record<string, SpeakerRole>;

export type TranscriptStatus = "queued" | "processing" | "completed" | "error";

/* ---------- Rubric ------------------------------------------------------ */

/** The fixed criteria every presentation is scored on. Weights sum to 100,
 *  so the overall score is a transparent weighted average (not an opaque
 *  number the model made up). */
